/**
 * @description This component for is a placholder of login flow
 * @returns JSX.Element
 */

const Login = (): JSX.Element => {
  const { setToken } = useAuth();
  const [password, setPassword] = useState("");
  const [showPassword, setShowPassword] = useState(false);
  const [error, setError] = useState("");
  const [presentAlert] = useIonAlert();

  return (
    <IonContent class="overflow-hidden login_container">
      <section>
        <img src={Logo} alt="app logo" />
        <form
          onSubmit={(event) => {
            event?.preventDefault();
            if (LOGIN_SECRET === password) {
              window.localStorage?.setItem("token", password);
              setToken(password);
            } else {
              setError("Invalid Password");
              presentAlert({
                message: "Invalid Password",
                header: "Oops!",
                buttons: [
                  {
                    text: "Cancel",
                    role: "cancel",
                  },
                  {
                    text: "OK",
                    role: "confirm",
                  },
                ],
              });
            }
          }}
        >
          <div>
            {error && <p className="error_text">{error}</p>}
            <IonInput
              className={`password_input ${error && "password_input_error"}`}
              type={showPassword ? "text" : "password"}
              placeholder="Password"
              value={password}
              clearInput
              onIonInput={(event: Event) => {
                setError("");
                const value = (event.target as HTMLIonInputElement)
                  .value as string;
                const regex = /^(?=.*[A-Za-z])(?=.*\d)[A-Za-z\d]{7,}$/;
                if (!regex.test(value)) {
                  setError("Please enter an 8 digit alphanumeric password");
                }
                setPassword(value);
              }}
            ></IonInput>
            <IonButton
              className="eye_icon"
              onClick={() => setShowPassword(!showPassword)}
            >
              {showPassword ? <EyeIcon /> : <EyeCloseIcon />}
            </IonButton>
          </div>
          <IonButton
            fill="solid"
            disabled={!!error}
            type="submit"
            className="login_btn"
          >
            Continue
            <svg
              width="11"
              height="21"
              viewBox="0 0 11 21"
              fill="none"
              xmlns="http://www.w3.org/2000/svg"
            >
              <path
                d="M1.42646 20.0919L1.42639 20.0919L1.4223 20.0875C1.07009 19.7044 1.07009 19.0783 1.4223 18.6952L7.95686 11.5883C8.37636 11.1321 8.37636 10.3848 7.95686 9.9286L1.4223 2.82173C1.07009 2.43866 1.07009 1.81249 1.4223 1.42942C1.78228 1.03791 2.38234 1.03791 2.74231 1.42942L9.27687 8.53629C10.4008 9.75867 10.4008 11.7583 9.27687 12.9806L2.74231 20.0875C2.5587 20.2872 2.32149 20.3839 2.08231 20.3839C1.83793 20.3839 1.60435 20.2724 1.42646 20.0919Z"
                fill="black"
                stroke="black"
                stroke-width="0.35"
              />
            </svg>
          </IonButton>
        </form>
      </section>
    </IonContent>
  );
};
export default Login;
